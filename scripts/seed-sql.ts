/**
 * Prints the production seed as SQL (same content as `npm run db:seed`), for applying through the Supabase SQL editor
 * or MCP when the service-role key is not at hand.   npx tsx scripts/seed-sql.ts > supabase/seed.sql
 */
import { toDb } from "../lib/db/map";
import { buildSeedTables } from "../lib/db/seed-data";
import { pkOf, TABLES } from "../lib/db/types";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) return `array[${v.map(lit).join(",")}]::text[]`;
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const tables = buildSeedTables("production");
const out: string[] = ["-- Production seed: real SATA content only. Generated by scripts/seed-sql.ts. Safe to re-run (inserts skip existing rows)."];
for (const t of TABLES) {
  const rows = tables[t] as object[];
  if (!rows.length) continue;
  const cols = [...new Set(rows.flatMap((r) => Object.keys(toDb(r))))];
  const values = rows.map((r) => { const d = toDb(r); return `(${cols.map((c) => lit(d[c])).join(",")})`; });
  const q = (c: string) => `"${c}"`;
  out.push(`insert into public.${t} (${cols.map(q).join(",")}) values\n${values.join(",\n")}\non conflict (${q(pkOf(t))}) do nothing;`);
}
console.log(out.join("\n\n"));
